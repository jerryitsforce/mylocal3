<?php
namespace Branch8\RoleDelegate\Controller\Adminhtml\Manage;

use Magento\Backend\App\Action;
use Magento\Backend\App\Action\Context;
use Magento\Framework\View\Result\PageFactory;

class Index extends Action
{
    const ADMIN_RESOURCE = 'Branch8_RoleDelegate::manage';
    private $resultPageFactory;

    public function __construct(Context $context, PageFactory $resultPageFactory)
    {
        parent::__construct($context);
        $this->resultPageFactory = $resultPageFactory;
    }

    public function execute()
    {
        $resultPage = $this->resultPageFactory->create();
        $resultPage->setActiveMenu('Branch8_RoleDelegate::manage');
        $resultPage->getConfig()->getTitle()->prepend(__('Role Delegation Management'));
        return $resultPage;
    }
}
